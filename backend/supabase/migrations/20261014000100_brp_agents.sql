create or replace function public.agent_begin_run(p_session_ref text default null, p_model text default null) returns jsonb
language plpgsql as $$
declare a text := brp.agent_name(); rid uuid := gen_random_uuid(); spec jsonb := brp.agent_read_spec();
begin
  if a is null then raise exception 'Agents only' using errcode = '42501'; end if;
  insert into public.agent_runs (run_id, agent, event, session_ref, model) values (rid, a, 'start', p_session_ref, p_model);
  return jsonb_build_object(
    'run_id', rid, 'agent', a, 'server_time', now(),
    'demo_clock', (select value from public.settings where key = 'demo_clock'),
    'installations', coalesce((select jsonb_agg(jsonb_build_object('id', i.id, 'name', i.name, 'mode', brp.agent_mode(a, i.id)) order by i.id)
                               from public.installations i), '[]'::jsonb),
    'readable_tables', coalesce((select jsonb_object_agg(k, spec->k->'cols') from jsonb_object_keys(spec) k
                                 where spec->k->'agents' ? a), '{}'::jsonb),
    'proposal_kinds', to_jsonb(brp.agent_kinds(a)),
    'money_rule', case when a = 'buyer_dispatch' then brp.money_rule() end,
    'rule', 'SHADOW MODE: you never act. Your only output is proposals with cited record ids. A person decides.');
end $$;

-- Read rows. p_filter: {"col": value} equals, {"col": [v1, v2]} any of, {"col": {"gte": x, "lte": y, "gt": x, "lt": y, "ilike": "%x%", "is_null": true}}.
create or replace function public.agent_read(p_table text, p_filter jsonb default '{}'::jsonb, p_limit int default 100,
                                             p_order text default null, p_desc boolean default false) returns jsonb
language plpgsql as $$
declare
  a text := brp.agent_name(); spec jsonb := brp.agent_read_spec() -> p_table;
  cols text[]; conds text[] := '{}'; k text; v jsonb; op text; ord text; out jsonb; lim int;
begin
  if a is null then raise exception 'Agents only' using errcode = '42501'; end if;
  if spec is null or not (spec->'agents' ? a) then raise exception 'Agent % may not read %', a, coalesce(p_table, 'null') using errcode = '42501'; end if;
  cols := array(select jsonb_array_elements_text(spec->'cols'));
  for k, v in select * from jsonb_each(coalesce(p_filter, '{}'::jsonb)) loop
    if not (k = any (cols)) then raise exception 'Unknown or unreadable column %.%', p_table, k using errcode = '22023'; end if;
    if jsonb_typeof(v) = 'array' then
      conds := conds || format('%I::text = any (%L::text[])', k, array(select jsonb_array_elements_text(v)));
    elsif jsonb_typeof(v) = 'object' then
      for op in select jsonb_object_keys(v) loop
        conds := conds || case op
          when 'gte' then format('%I >= %L', k, v->>op) when 'lte' then format('%I <= %L', k, v->>op)
          when 'gt' then format('%I > %L', k, v->>op)   when 'lt' then format('%I < %L', k, v->>op)
          when 'ilike' then format('%I::text ilike %L', k, v->>op)
          when 'is_null' then format('%I is %s null', k, case when (v->>op)::boolean then '' else 'not' end)
          else null end;
        if conds[cardinality(conds)] is null then raise exception 'Unknown filter operator %', op using errcode = '22023'; end if;
      end loop;
    elsif jsonb_typeof(v) = 'null' then
      conds := conds || format('%I is null', k);
    else
      conds := conds || format('%I::text = %L', k, v #>> '{}');
    end if;
  end loop;
  ord := coalesce(p_order, spec->>'key');
  if not (ord = any (cols)) then raise exception 'Cannot order by %', ord using errcode = '22023'; end if;
  lim := least(greatest(coalesce(p_limit, 100), 1), 500);
  execute format('select coalesce(jsonb_agg(to_jsonb(t)), ''[]''::jsonb) from (select %s from public.%I %s order by %I %s nulls last limit %s) t',
    (select string_agg(format('%I', c), ', ') from unnest(cols) c), p_table,
    case when cardinality(conds) > 0 then 'where ' || array_to_string(conds, ' and ') else '' end,
    ord, case when p_desc then 'desc' else 'asc' end, lim) into out;
  return jsonb_build_object('table', p_table, 'count', jsonb_array_length(out), 'limit', lim, 'rows', out);
end $$;

create or replace function public.agent_propose(p_inst text, p_kind text, p_payload jsonb, p_rationale text, p_cited_ids text[], p_run_id uuid default null)
returns jsonb language plpgsql as $$
declare pid text; pstatus text; pflags text[]; pappr text; pchecks jsonb;
begin
  if brp.agent_name() is null then raise exception 'Agents only' using errcode = '42501'; end if;
  insert into public.agent_proposals (run_id, agent, inst, kind, payload, rationale, cited_ids)
  values (p_run_id, brp.agent_name(), p_inst, p_kind, coalesce(p_payload, '{}'::jsonb), p_rationale, p_cited_ids)
  returning id, status, flags, approver_required, checks into pid, pstatus, pflags, pappr, pchecks;   -- only columns brp_agent may read
  return jsonb_build_object('id', pid, 'status', pstatus, 'mode', brp.agent_mode(brp.agent_name(), p_inst), 'flags', to_jsonb(pflags),
    'approver_required', pappr, 'checks', pchecks,
    'note', 'Recorded as a proposal. Nothing was executed. A person approves or rejects it.');
end $$;

create or replace function public.agent_end_run(p_run_id uuid, p_ok boolean default true, p_summary text default null, p_counts jsonb default '{}'::jsonb)
returns jsonb language plpgsql as $$
declare a text := brp.agent_name();
begin
  if a is null then raise exception 'Agents only' using errcode = '42501'; end if;
  if not exists (select 1 from public.agent_runs r where r.run_id = p_run_id and r.event = 'start') then
    raise exception 'No run % was started by %', p_run_id, a using errcode = '22023';
  end if;
  insert into public.agent_runs (run_id, agent, event, summary, counts)
  values (p_run_id, a, case when p_ok then 'finish' else 'error' end, p_summary, coalesce(p_counts, '{}'::jsonb));
  return jsonb_build_object('run_id', p_run_id, 'logged', true,
    'proposals', (select count(*) from public.agent_proposals p where p.run_id = p_run_id));
end $$;

-- The reply checker (backend/agents/reply-checker.mjs) logs what it removed from a draft reply before it was sent.
create or replace function public.agent_log_reply_check(p_run_id uuid, p_removed jsonb, p_summary text default null, p_counts jsonb default '{}'::jsonb)
returns jsonb language plpgsql as $$
declare a text := brp.agent_name();
begin
  if a is null then raise exception 'Agents only' using errcode = '42501'; end if;
  if jsonb_typeof(p_removed) <> 'array' then raise exception 'removed must be a JSON array' using errcode = '22023'; end if;
  insert into public.agent_runs (run_id, agent, event, summary, counts)
  values (p_run_id, a, 'reply_check', left(p_summary, 4000), coalesce(p_counts, '{}'::jsonb) || jsonb_build_object('removed', p_removed));
  return jsonb_build_object('run_id', p_run_id, 'logged', true, 'removed', jsonb_array_length(p_removed));
end $$;

-- ---------------------------------------------------------------------------
-- People: decide a proposal, set an agent's mode (Admin only)
-- ---------------------------------------------------------------------------
create or replace function public.agent_proposal_decide(p_id text, p_decision text, p_note text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p public.agent_proposals; d text := lower(trim(coalesce(p_decision, '')));
begin
  if not brp.is_admin() then raise exception 'Admin only' using errcode = '42501'; end if;
  if d in ('approve','approved') then d := 'approved'; elsif d in ('reject','rejected') then d := 'rejected';
  else raise exception 'Decision must be approve or reject' using errcode = '22023'; end if;
  select * into p from public.agent_proposals where id = p_id for update;
  if not found then raise exception 'No proposal %', p_id using errcode = '22023'; end if;
  if brp.is_demo_admin() and not p.sample then raise exception 'The demo admin can decide sample proposals only' using errcode = '42501'; end if;
  if p.status <> 'proposed' then raise exception 'Proposal % was already %', p_id, p.status using errcode = '22023'; end if;
  if d = 'rejected' and coalesce(trim(p_note), '') = '' then raise exception 'Say why you rejected it' using errcode = '22023'; end if;
  perform set_config('brp.agent_decide', 'on', true);
  update public.agent_proposals set status = d, decided_by = auth.uid(), decided_by_email = (select email from public.profiles where id = auth.uid()),
         decided_at = now(), decision_note = nullif(trim(p_note), '')
  where id = p_id returning * into p;
  perform set_config('brp.agent_decide', 'off', true);
  return to_jsonb(p);
end $$;

create or replace function public.admin_set_agent_mode(p_agent text, p_inst text, p_mode text, p_note text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare s public.agent_settings; i text := coalesce(nullif(trim(p_inst), ''), '*');
begin
  if not brp.is_admin() then raise exception 'Admin only' using errcode = '42501'; end if;
  if p_mode not in ('off','shadow','supervised','live') then raise exception 'Mode must be off, shadow, supervised or live' using errcode = '22023'; end if;
  if brp.is_demo_admin() and p_mode in ('supervised','live') then
    raise exception 'The demo admin can set off or shadow only' using errcode = '42501';
  end if;
  if i <> '*' and not exists (select 1 from public.installations where id = i) then raise exception 'Unknown installation %', i using errcode = '22023'; end if;
  insert into public.agent_settings (agent, inst, mode, note, updated_by) values (p_agent::public.brp_agent_name, i, p_mode, p_note, auth.uid())
  on conflict (agent, inst) do update set mode = excluded.mode, note = excluded.note, updated_by = excluded.updated_by
  returning * into s;
  return to_jsonb(s);
end $$;

