create table public.agent_settings (
  agent       public.brp_agent_name not null,
  inst        text not null default '*' check (inst = '*' or inst ~ '^[A-Za-z0-9-]{2,40}$'),   -- '*' = all installations
  mode        text not null default 'off' check (mode in ('off','shadow','supervised','live')),
  note        text,
  updated_at  timestamptz not null default now(),
  updated_by  uuid,
  primary key (agent, inst)
);

create table public.agent_runs (
  id           bigint generated by default as identity primary key,
  run_id       uuid not null,
  agent        public.brp_agent_name not null,
  event        text not null check (event in ('start','finish','error','reply_check')),   -- reply_check: the reply checker's removed claims
  at           timestamptz not null default now(),
  session_ref  text check (session_ref is null or length(session_ref) <= 200),   -- Managed Agents session or deployment run id, when known
  model        text check (model is null or length(model) <= 100),
  summary      text check (summary is null or length(summary) <= 4000),
  counts       jsonb not null default '{}'::jsonb
);
create index agent_runs_run on public.agent_runs (run_id);
create index agent_runs_agent_at on public.agent_runs (agent, at desc);

create table public.agent_proposals (
  id                 text primary key default ('AP-' || lpad(nextval('public.agent_prop_seq')::text, 5, '0')),
  run_id             uuid,
  agent              public.brp_agent_name not null,
  inst               text not null references public.installations(id) deferrable initially deferred,
  kind               text not null,
  payload            jsonb not null default '{}'::jsonb,
  rationale          text not null check (length(rationale) between 10 and 4000),
  cited_ids          text[] not null check (cardinality(cited_ids) between 1 and 50),
  flags              text[] not null default '{}',
  checks             jsonb not null default '{}'::jsonb,      -- server checks, e.g. the money rule result
  approver_required  text check (approver_required in ('site_lead','program_manager')),
  mode_at_proposal   text not null default 'shadow' check (mode_at_proposal in ('shadow','supervised','live')),
  status             text not null default 'proposed' check (status in ('proposed','approved','rejected')),
  decided_by         uuid,
  decided_by_email   text,
  decided_at         timestamptz,
  decision_note      text check (decision_note is null or length(decision_note) <= 2000),
  sample             boolean not null default false,
  created_at         timestamptz not null default now()
);
create index agent_proposals_status on public.agent_proposals (status, created_at desc);
create index agent_proposals_agent_inst on public.agent_proposals (agent, inst, created_at desc);

