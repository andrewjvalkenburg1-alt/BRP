create or replace function brp.agent_runs_before_insert() returns trigger
language plpgsql as $$
begin
  if brp.agent_name() is not null then new.agent := brp.agent_name(); end if;
  new.at := now();
  return new;
end $$;
create trigger brp_agent_runs_before_insert before insert on public.agent_runs for each row execute function brp.agent_runs_before_insert();

create or replace function brp.agent_proposal_before_insert() returns trigger
language plpgsql as $$
declare mode text; missing text[]; total numeric; chk jsonb; line_sum numeric;
begin
  if brp.agent_name() is not null then new.agent := brp.agent_name(); end if;   -- an agent cannot propose as another agent
  new.status := 'proposed'; new.decided_by := null; new.decided_by_email := null; new.decided_at := null; new.decision_note := null;
  new.flags := '{}'; new.checks := '{}'::jsonb; new.approver_required := null;
  if not brp.bulk() then new.created_at := now(); end if;

  mode := brp.agent_mode(new.agent, new.inst);
  if mode = 'off' then
    raise exception 'Agent % is off for installation %', new.agent, new.inst using errcode = '42501';
  end if;
  new.mode_at_proposal := mode;

  if not (new.kind = any (brp.agent_kinds(new.agent))) then
    raise exception 'Agent % cannot propose kind % (allowed: %)', new.agent, new.kind, array_to_string(brp.agent_kinds(new.agent), ', ') using errcode = '22023';
  end if;
  if jsonb_typeof(new.payload) <> 'object' then raise exception 'payload must be a JSON object' using errcode = '22023'; end if;

  missing := brp.unknown_ids(new.cited_ids);
  if cardinality(missing) > 0 then
    raise exception 'Cited record ids not found: %. Cite only records that exist.', array_to_string(missing, ', ') using errcode = '22023';
  end if;

  if new.kind = 'purchase_order' then
    total := case when jsonb_typeof(new.payload->'total') = 'number' then (new.payload->>'total')::numeric end;
    if total is null or total <= 0 then
      raise exception 'A purchase_order proposal needs payload.total, the full order total in USD including shipping' using errcode = '22023';
    end if;
    chk := public.buyer_spend_check(new.inst, total, now());
    new.checks := jsonb_build_object('money', chk);
    if (chk->>'needs_approval')::boolean then
      if coalesce(new.payload->>'approval_level', '') = 'auto' then
        raise exception 'Over the money rule (%): this order needs % approval and cannot be auto-approved',
          array_to_string(array(select jsonb_array_elements_text(chk->'reasons')), '; '), chk->>'approver' using errcode = '22023';
      end if;
      new.flags := array(select jsonb_array_elements_text(chk->'codes'));
      new.approver_required := chk->>'approver';
    end if;
    if jsonb_typeof(new.payload->'lines') = 'array' then
      select sum((l->>'qty')::numeric * (l->>'unit_cost')::numeric) into line_sum from jsonb_array_elements(new.payload->'lines') l;
      if line_sum is not null and abs(line_sum + coalesce((new.payload->>'shipping')::numeric, 0) - total) > 0.01 then
        new.flags := new.flags || 'total_mismatch'::text;
      end if;
    end if;
  end if;
  return new;
end $$;
create trigger brp_agent_proposal_before_insert before insert on public.agent_proposals for each row execute function brp.agent_proposal_before_insert();

-- Only the decision fields change, and only through agent_proposal_decide.
create or replace function brp.agent_proposal_before_update() returns trigger
language plpgsql as $$
begin
  if coalesce(current_setting('brp.agent_decide', true), '') <> 'on' then
    raise exception 'Proposals change only through agent_proposal_decide' using errcode = '42501';
  end if;
  if (to_jsonb(new) - array['status','decided_by','decided_by_email','decided_at','decision_note'])
     is distinct from (to_jsonb(old) - array['status','decided_by','decided_by_email','decided_at','decision_note']) then
    raise exception 'Only the decision can change on a proposal' using errcode = '42501';
  end if;
  return new;
end $$;
