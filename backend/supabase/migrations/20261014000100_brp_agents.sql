-- BRP One backend, migration 4: operations agents in shadow mode.
--
-- What this adds
--   agent_settings   per agent and per installation: off | shadow | supervised | live. '*' is the default row for all
--                    installations; a row for one installation overrides it. No row means off.
--   agent_runs       append-only run log (one 'start' row and one 'finish' or 'error' row per run, plus one
--                    'reply_check' row per checked reply for agents that talk to people; see agents/reply-checker.mjs).
--   agent_proposals  what an agent would do, with its rationale and the record ids it cites. People approve or reject.
--                    In shadow mode an approval records agreement only. Nothing is executed.
--   brp_agent        a Postgres role for the agents. It READS the operations tables it needs (column by column, so
--                    Soldier names and account ids are never readable) and INSERTS only into agent_runs and
--                    agent_proposals. It has no UPDATE or DELETE on anything.
--   buyer_weekly_cap / buyer_spend_check   Andrew's money rule, per installation (see below).
--
-- How an agent is identified (the JWT-claim path)
--   The caller is in role brp_agent and request.jwt.claims carries {"brp_agent": "<agent name>"}. Two ways to get there:
--   1. The agent-mcp Edge Function (supabase/functions/agent-mcp) opens a transaction on the server's own database
--      connection and runs `set local role brp_agent` plus `set_config('request.jwt.claims', ...)` before every call.
--   2. PostgREST with a JWT whose claims are {"role": "brp_agent", "brp_agent": "<name>"}, signed with the project's
--      JWT secret. PostgREST switches to the role named in the token. (Only possible where you can mint such a token.)
--   brp.agent_name() trusts the claim only while the session role is brp_agent, so a signed-in person cannot use it.
--
-- The money rule (Andrew, Oct 2026), per installation
--   Per order: $500 (assumed fixed; Andrew has not confirmed). Per week: $2,500, weeks start Monday.
--   Once an installation has 3 months of spend history, its weekly cap is its trailing 13-week average weekly spend
--   plus 10%, and never more than that. Over either limit: that installation's site lead approves; over $2,500 for one
--   order: the program manager. Spend = purchase orders issued (issued_at set) and not cancelled. The numbers live in
--   settings.buyer_money_rule so they can change without a migration. This matches the agent bench (world.py).

-- ---------------------------------------------------------------------------
-- Names
-- ---------------------------------------------------------------------------
create domain public.brp_agent_name as text
  check (value in ('buyer_dispatch','sensor_watch','inspection_scheduler','room_readiness','soldier_liaison'));

create sequence public.agent_prop_seq start 1;   -- AP-00001

do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'brp_agent') then create role brp_agent nologin noinherit; end if;
end $$;
-- Supabase: PostgREST connects as authenticator and switches role per request; the server's postgres login must be
-- able to SET ROLE brp_agent for the agent-mcp function. Neither role exists on a bare local Postgres.
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'authenticator') then execute 'grant brp_agent to authenticator'; end if;
  if exists (select 1 from pg_roles where rolname = 'postgres' and not rolsuper) then execute 'grant brp_agent to postgres'; end if;
exception when others then raise notice 'brp_agent role grant skipped: %', sqlerrm;
end $$;

