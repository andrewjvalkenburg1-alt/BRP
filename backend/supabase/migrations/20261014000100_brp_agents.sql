-- true when the calling agent's read list includes this table. All agents share the brp_agent role, so the per-agent
-- list is enforced here in the row policies as well as in agent_read.
create or replace function brp.agent_may_read(p_table text) returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(brp.agent_read_spec() -> p_table -> 'agents' ? brp.agent_name(), false)
$$;

-- Record ids in p_ids that match no BRP record. An agent may cite only records that exist (honesty rule 2).
create or replace function brp.unknown_ids(p_ids text[]) returns text[]
language sql stable security definer set search_path = '' as $$
  select coalesce(array_agg(x order by x), '{}') from unnest(p_ids) x
  where not exists (select 1 from public.work_orders where id = x)
    and not exists (select 1 from public.purchase_orders where id = x)
    and not exists (select 1 from public.rooms where id = x)
    and not exists (select 1 from public.buildings where id = x)
    and not exists (select 1 from public.installations where id = x)
    and not exists (select 1 from public.parts where sku = x)
    and not exists (select 1 from public.catalog_items where id = x)
    and not exists (select 1 from public.vendors where id = x)
    and not exists (select 1 from public.cabinets where id = x)
    and not exists (select 1 from public.purchase_list where id = x)
    and not exists (select 1 from public.alerts where id = x)
    and not exists (select 1 from public.agent_proposals where id = x)
    and not exists (select 1 from public.wo_events where x ~ '^WOE-\d+$' and id = substr(x, 5)::bigint)
$$;

-- May the caller see money for this installation? Agents: when switched on there. People: active staff in scope.
-- Direct database sessions with no request claims (migrations, psql, the service role) are allowed.
create or replace function brp.caller_sees_inst(p_inst text) returns boolean
language sql stable security definer set search_path = '' as $$
  select case
    when coalesce(current_setting('role', true), '') = 'brp_agent' then brp.agent_sees(p_inst)
    when auth.uid() is not null then
      brp.my_role() = any (array['admin','program_manager','site_lead','barracks_manager','buyer','cor','commander'])
      and (brp.sees_all() or brp.my_inst() = p_inst)
    else coalesce(current_setting('role', true), 'none') in ('none', 'service_role')
         or coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role', '') = 'service_role'
  end
$$;

create or replace function brp.money_rule() returns jsonb
language sql stable security definer set search_path = '' as $$
  select '{"per_order_limit": 500, "weekly_cap_default": 2500, "history_months": 3, "trailing_weeks": 13, "max_over_average": 0.10,
           "site_lead_max": 2500, "week_tz": "America/Chicago", "history_since": {}}'::jsonb
         || coalesce((select value from public.settings where key = 'buyer_money_rule'), '{}'::jsonb)
$$;

-- ---------------------------------------------------------------------------
-- The weekly cap. Returns the cap in force at p_at and how it was set.
-- ---------------------------------------------------------------------------
create or replace function public.buyer_weekly_cap(p_inst text, p_at timestamptz default now()) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  r jsonb := brp.money_rule();
  tz text := r->>'week_tz';
  months int := (r->>'history_months')::int;
  weeks int := (r->>'trailing_weeks')::int;
  tol numeric := (r->>'max_over_average')::numeric;
  def numeric := (r->>'weekly_cap_default')::numeric;
  since timestamptz; switch_at timestamptz; cw timestamp; spent numeric; avg_ numeric;
begin
  if p_inst is null or not exists (select 1 from public.installations i where i.id = p_inst) then
    raise exception 'Unknown installation %', p_inst using errcode = '22023';
  end if;
  if not brp.caller_sees_inst(p_inst) then raise exception 'Not allowed for installation %', p_inst using errcode = '42501'; end if;

  since := coalesce((r->'history_since'->>p_inst)::timestamptz,
                    (select min(p.issued_at) from public.purchase_orders p
                     where p.inst = p_inst and p.issued_at is not null and p.status <> 'cancelled'));
  cw := date_trunc('week', p_at at time zone tz);                      -- Monday 00:00 local
  if since is not null then switch_at := ((since at time zone tz) + make_interval(months => months)) at time zone tz; end if;

  if since is null or p_at < switch_at then
    return jsonb_build_object('installation', p_inst, 'as_of', p_at, 'week_of', cw::date, 'weekly_cap', round(def, 2), 'rule', 'default',
      'history_since', since, 'trailing_average_from', switch_at,
      'detail', format('less than %s months of spend history (since %s): weekly cap $%s', months, coalesce(since::date::text, 'none'), to_char(def, 'FM999999990.00')));
  end if;

  select coalesce(sum(p.total), 0) into spent from public.purchase_orders p
  where p.inst = p_inst and p.issued_at is not null and p.status <> 'cancelled'
    and (p.issued_at at time zone tz) >= cw - make_interval(weeks => weeks)
    and (p.issued_at at time zone tz) <  cw;
  avg_ := spent / weeks;

  return jsonb_build_object('installation', p_inst, 'as_of', p_at, 'week_of', cw::date,
    'weekly_cap', round(avg_ * (1 + tol), 2), 'rule', 'trailing_average',
    'history_since', since, 'trailing_average_from', switch_at,
    'trailing_weeks', weeks, 'from_week', (cw - make_interval(weeks => weeks))::date, 'to_week', (cw - interval '1 week')::date,
    'trailing_spend', round(spent, 2), 'average_weekly_spend', round(avg_, 2), 'max_over_average', tol,
    'detail', format('%s months of history: cap = trailing %s-week average $%s + %s%%', months, weeks, to_char(avg_, 'FM999999990.00'), round(tol * 100)));
end $$;

-- Would an order of p_amount at this installation need approval right now, and from whom?
create or replace function public.buyer_spend_check(p_inst text, p_amount numeric, p_at timestamptz default now()) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  r jsonb := brp.money_rule();
  tz text := r->>'week_tz';
  per_order numeric := (r->>'per_order_limit')::numeric;
  sl_max numeric := (r->>'site_lead_max')::numeric;
  cap jsonb; wk numeric; reasons text[] := '{}'; codes text[] := '{}'; approver text := null; cw timestamp;
begin
  if p_amount is null or p_amount <= 0 then raise exception 'Order total must be more than $0' using errcode = '22023'; end if;
  cap := public.buyer_weekly_cap(p_inst, p_at);
  cw := date_trunc('week', p_at at time zone tz);
  select coalesce(sum(p.total), 0) into wk from public.purchase_orders p
  where p.inst = p_inst and p.issued_at is not null and p.status <> 'cancelled'
    and (p.issued_at at time zone tz) >= cw and p.issued_at <= p_at;

  if p_amount > per_order + 0.005 then
    reasons := reasons || format('order total $%s is over the $%s per-order limit', to_char(p_amount, 'FM999999990.00'), to_char(per_order, 'FM999999990'));
    codes := codes || 'over_per_order_limit'::text;
  end if;
  if wk + p_amount > (cap->>'weekly_cap')::numeric + 0.005 then
    reasons := reasons || format('week-to-date spend $%s + this order $%s = $%s is over the weekly cap $%s', to_char(wk, 'FM999999990.00'),
      to_char(p_amount, 'FM999999990.00'), to_char(wk + p_amount, 'FM999999990.00'), to_char((cap->>'weekly_cap')::numeric, 'FM999999990.00'));
    codes := codes || 'over_weekly_cap'::text;
  end if;
  if cardinality(codes) > 0 then approver := 'site_lead'; end if;
  if p_amount > sl_max + 0.005 then approver := 'program_manager'; codes := codes || 'over_site_lead_authority'::text; end if;

  return jsonb_build_object('installation', p_inst, 'amount', round(p_amount, 2), 'per_order_limit', per_order,
    'per_order_limit_confirmed', coalesce((r->>'per_order_confirmed')::boolean, false),
    'week_of', cap->'week_of', 'week_spend_before', round(wk, 2), 'weekly_cap', cap->'weekly_cap', 'cap_basis', cap,
    'needs_approval', cardinality(codes) > 0, 'approver', coalesce(approver, 'auto'), 'reasons', to_jsonb(reasons), 'codes', to_jsonb(codes));
end $$;

