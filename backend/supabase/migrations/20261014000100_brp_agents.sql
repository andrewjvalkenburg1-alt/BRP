-- The calling agent, or null. Trusted only while the session role is brp_agent (current_setting('role') keeps that
-- value inside security definer functions, where current_user changes).
create or replace function brp.agent_name() returns text
language sql stable as $$
  select case when coalesce(current_setting('role', true), '') = 'brp_agent'
              and (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'brp_agent')
                  in ('buyer_dispatch','sensor_watch','inspection_scheduler','room_readiness','soldier_liaison')
         then nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'brp_agent' end
$$;

-- Effective mode: the installation's row, else the '*' row, else off.
create or replace function brp.agent_mode(p_agent text, p_inst text) returns text
language sql stable security definer set search_path = '' as $$
  select coalesce((select s.mode from public.agent_settings s where s.agent = p_agent and s.inst = p_inst),
                  (select s.mode from public.agent_settings s where s.agent = p_agent and s.inst = '*'),
                  'off')
$$;

-- true when the calling agent is switched on (any mode but off) for that installation. Switching an agent off for an
-- installation hides that installation's data from it, as well as stopping its proposals.
create or replace function brp.agent_sees(p_inst text) returns boolean
language sql stable security definer set search_path = '' as $$
  select brp.agent_name() is not null and p_inst is not null and brp.agent_mode(brp.agent_name(), p_inst) <> 'off'
$$;

-- What each agent may propose.
create or replace function brp.agent_kinds(p_agent text) returns text[]
language sql immutable as $$
  select case p_agent
    when 'buyer_dispatch'       then array['purchase_order','quote_request','dispatch','priority','human_task','backorder_decision','wo_note']
    when 'sensor_watch'         then array['sensor_work_order','page_oncall','sensor_dismiss','sensor_maintenance']
